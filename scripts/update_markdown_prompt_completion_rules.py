#!/usr/bin/env python3
"""Append idempotent repository-batch completion rules to the Markdown prompt."""
from pathlib import Path

PATH = Path('.prompt/Markdown文档整理与修复通用提示词.md')
MARKER = '## 仓库批处理：完成判定与防漏检规则'
BLOCK = r'''

---

## 仓库批处理：完成判定与防漏检规则

当任务要求处理 `temp/` 中全部 Markdown 时，**不能以“脚本运行过”“文件最近被修改过”“Git 历史存在 format/cleanup/finalize 提交”“旧进度报告标记已完成”作为完成依据**。这些信息只能作为弱辅助证据，最终必须以当前文件内容为准。

### 1. 每轮都要重新递归扫描当前内容

- 递归枚举 `temp/**/*.md`，不得只读取旧的待处理名单或旧进度 JSON；
- 新增、改名、移动过的文件必须重新进入检查；
- 文件修改时间、最后提交时间、提交信息只用于帮助定位可疑文件，**不能直接判定“已格式化”**；
- 若 Git 历史显示“已格式化”，但当前内容仍违反本提示词，则以当前内容为准，重新修复。

### 2. “完成”必须同时通过内容级验收

至少检查以下项目：

1. 全文只有一个一级标题 `#`，且为书名/文档主标题；
2. 长文不能只有书名而完全没有正文结构；应结合当前内容恢复真实章节、小节层级；
3. 不得残留已抽取的顶部文字目录；原始目录页图片如属于需要保留的图片引用，则继续保留；
4. 不得把目录项本身误当正文标题；正文标题应在正文实际出现位置恢复；
5. 检查“标题与第一句正文粘连”，例如 `小节标题正文第一句……`，必须拆成标题与正文；
6. 检查显式章节标记是否仍未恢复，例如 `□如何……正文`、独立的“第X章/第X节/第X课”等；
7. 检查标题层级跳级、异常巨大标题、把整段正文误升为标题、OCR 乱码标题；
8. 检查正文中的页码、页眉页脚、转换器标记、`视觉补充`、`<!-- page:N -->` 等残留；
9. 检查异常超长 OCR 行、明显未分段的整页文本，并判断是否仍需结构整理；
10. Markdown 图片引用必须逐条守恒：路径、文件名、顺序和出现次数不得因格式化被破坏；
11. URL、代码块、表格、引用块等特殊结构必须继续满足本提示词中的保护规则；
12. 对无法高置信自动修复的文件，必须列入 `needs_review`，不能为了让报告显示 0 问题而强行修改或忽略。

### 3. 必须识别“假通过”

以下情况均视为**假通过**，不得宣告完成：

- 文件有近期修改记录，但正文仍是原始 OCR 连续文本；
- 文件只有 `# 书名`，长篇正文没有任何章节/小节；
- 文件已有很多后半部分标题，但前半部分仍存在大量标题与正文粘连；
- 旧脚本因缺少某种页面标记而跳过正文格式化；
- 顶部目录被部分删除，但目录文本或目录编号仍残留；
- 自动校验只检查 Markdown 语法，却没有检查语义标题覆盖率；
- 历史提交名包含 `format` / `cleanup` / `finalize`，但当前内容仍不合格。

### 4. 推荐的仓库级验收输出

批处理结束后应生成或更新一份内容级审计报告，至少包含：

- 扫描的 Markdown 总数；
- 实际修改文件数；
- 通过文件数；
- 高风险 / 中风险待人工或深度语义检查文件数；
- 目录残留、显式章节标记残留、标题粘连、标题密度异常、超长 OCR 行等问题计数；
- 图片引用总数与守恒结果；
- 每个仍未通过文件的具体路径、问题类型和证据；
- 对“历史显示已处理但当前内容失败”的单独标记。

批处理的最终目标不是“脚本成功退出”，而是：

> **当前 `temp/` 中每个 Markdown 文件都经过内容级重新检查；能安全修复的已修复；不能安全自动修复的被明确列出，且不存在用修改日期、旧报告或提交信息掩盖的遗漏。**
'''

text = PATH.read_text(encoding='utf-8-sig')
if MARKER not in text:
    PATH.write_text(text.rstrip() + BLOCK + '\n', encoding='utf-8')
    print('appended content-based completion rules')
else:
    print('completion rules already present')
