#!/usr/bin/env python3
from __future__ import annotations
from pathlib import Path

PATH = Path('.prompt/Markdown文档整理与修复通用提示词.md')
MARKER = '### 5. “确定缺陷”与“复核候选”必须分开统计'
APPEND = r'''

### 5. “确定缺陷”与“复核候选”必须分开统计

仓库批量处理时，**禁止把高召回启发式候选直接当成格式错误**。最终报告至少分为两层：

#### A. 确定缺陷（Actionable Defects）

只有当前文件内容能够直接证明的问题，才允许阻塞“完成”状态，典型包括：

- H1 数量不是 1；
- 超长文档只有书名、几乎没有正文结构；
- 明确的 `□` / `▢` 小节标记仍混在正文；
- `第X章 / 第X节 / 第X课 / 第X讲 / 第X篇 / 第X卷 / 第X册` 等真实章节标记仍是普通正文；
- 标题与大段正文错误合并成超长 Markdown 标题；
- 原始文字目录、点线页码目录仍残留；
- `<!-- page:N -->`、视觉补充、转换标签等中间产物仍残留；
- 整页 OCR 被压成异常超长单行；
- 实际微信号、账号、已知公号水印、明确引流 CTA 等可执行推广凭据仍存在；
- 图片引用数量或引用字符串发生非预期变化。

这类问题可以进入自动修复，但仍必须经过图片守恒、H1 守恒、目标锚点唯一性等安全校验。

#### B. 复核候选（Review Candidates）

下面这些只能提示“值得检查”，**不能单独证明文件有错，也不能据此自动修改正文**：

- 标题密度偏低；
- 疑似“标题 + 正文”粘连；
- 普通句子包含“微信 / 加微信 / 微信号”等词；
- 某些编号 `1 / 2 / 3` 看起来像小节；
- 某些短句看起来像标题；
- Git 历史显示曾经格式化，但当前启发式仍有候选。

例如：

```text
记住：你如果想要从未得到过的东西，就要去做从未做过的事。
```

它可能只是普通正文，不能因为“记住：”或后面出现“如果”就自动升为标题。

又例如：

```text
你加我微信，我就可以送你一个什么东西……
```

如果上下文是在讲营销案例，这属于正文内容，不能仅凭“加我微信”四个字删除。

因此最终验收必须分别输出：

```text
确定缺陷：0 / N
复核候选：M / N
```

只有“确定缺陷 = 0”才表示通过客观验收；复核候选可以继续人工抽查，但不得伪装成确定错误。

### 6. 推广与广告残留必须按“可执行凭据 / 明确 CTA”判定

删除广告时，不得使用“只要包含微信、公众号、加微信就删除”的宽泛规则。

优先删除以下高置信内容：

- 实际微信号、手机号、账号字符串；
- `微信：xxx`、`WX: xxx`、`VX: xxx`、`薇芯：xxx` 等明确联系方式；
- 已确认的重复公号水印，如 `公众号：某账号名`；
- `扫码关注，回复……`；
- `添加作者获取内部分享`；
- `更多资料加……`；
- `添加作者微信……获取内部分享`；
- 其他明显脱离正文、用于导流或售卖的完整 CTA 语义单元。

必须保留：

- 正文讨论微信、私域、公众号、社群、获客方式的案例；
- 小说、案例、访谈里人物“加微信”的叙述；
- 技术或商业分析中对微信生态的正常说明。

如果联系方式被 OCR 换行拆开，例如：

```text
微信：
abc12345
```

应允许跨行识别，但删除时仍只删除已确认的推广凭据或完整 CTA，**不得顺便改空格、括号、标点或邻接正文**。

### 7. 批量格式化的最终通过条件

对 `temp` 目录做全量处理后，至少执行以下终检：

```text
1. 扫描全部 Markdown，而不是只扫描本轮修改过的文件；
2. 每份文档恰好一个 H1；
3. 确定缺陷数量为 0；
4. 显式推广凭据 / 明确 CTA 专项扫描为 0；
5. Markdown 图片引用总量与逐文件引用集合守恒；
6. 复核候选单独输出，不影响客观通过状态；
7. 修改日期、最近提交、脚本是否执行成功，只能作为辅助记录，不能作为“已完成”的证据。
```

最终报告建议使用：

```text
扫描文件数：N
客观通过：N/N
确定高风险缺陷：0
确定中风险缺陷：0
显式推广凭据：0
图片引用：守恒
复核候选文件：M（仅供后续人工抽查，不等同于错误）
```

若历史上曾有 `format / cleanup / finalize / repair` 提交，而当前内容仍存在确定缺陷，应标记为：

> **历史已处理，但当前内容未通过（false pass）**

不得因为文件“最近改过”而跳过。
'''


def main() -> int:
    text = PATH.read_text(encoding='utf-8-sig')
    if MARKER in text:
        print('Completion-review rules already present; no change.')
        return 0
    if not text.endswith('\n'):
        text += '\n'
    PATH.write_text(text.rstrip() + APPEND + '\n', encoding='utf-8')
    print('Appended semantic completion, review-candidate, and promo rules.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
